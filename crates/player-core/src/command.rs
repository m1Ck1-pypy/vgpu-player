//! Команды управления из UI в ядро.

use std::time::Duration;

use crate::Source;
use crate::http_options::HttpOptions;

/// Что UI может попросить у ядра.
///
/// Набор фиксирован спецификацией (`docs/SPEC.md`, раздел 5), поэтому команды
/// появляются даже раньше, чем ядро учится их выполнять.
///
/// `Eq` не выводится: в `SetVolume` лежит `f32`, а у плавающей точки нет
/// полного порядка.
#[derive(Debug, Clone, PartialEq)]
pub enum Command {
    /// Открыть файл или URL и подготовить дорожки.
    ///
    /// Заголовки HTTP-источника — значения по умолчанию; явные
    /// `Referer`/`User-Agent` передаются в [`Command::OpenWith`].
    Open(Source),
    /// Открыть источник с явными заголовками HTTP.
    OpenWith { source: Source, http: HttpOptions },
    /// Продолжить воспроизведение.
    Play,
    /// Приостановить воспроизведение.
    Pause,
    /// Перейти к позиции.
    Seek(Duration),
    /// Перейти на шаг вперёд или назад от текущей позиции ядра.
    ///
    /// Относительная цель считается в ядре: при удержании клавиши
    /// `PositionChanged` доходят до UI с задержкой, и абсолютная цель,
    /// посчитанная в UI, откатывалась бы назад.
    SeekRelative { forward: bool, step: Duration },
    /// Изменить громкость: `1.0` — исходный уровень.
    SetVolume(f32),
    /// Остановить воспроизведение и завершить поток ядра.
    Stop,
}
